// Copies the curriculum into web/curriculum and bundles harnesses + reference solutions for the browser.
// usage: node tools/build.js
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "..");
const SRC = path.join(ROOT, "curriculum"), OUT = path.join(ROOT, "web", "curriculum");
const ORDER = ["_core", "_world", "_dossiers", "_engine", "python", "javascript", "typescript", "sql", "bash", "go", "rust", "swift", "kotlin", "java", "csharp", "cpp"];

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
for (const f of ORDER) fs.copyFileSync(path.join(SRC, f + ".js"), path.join(OUT, f + ".js"));

const bundle = (dir, key) => {
  const map = {};
  for (const f of fs.readdirSync(path.join(SRC, dir)).sort()) map[f.replace(/\.[^.]+$/, "")] = fs.readFileSync(path.join(SRC, dir, f), "utf8");
  return `// generated by tools/build.js. Do not edit.\n(function (g) { const RA = g.RA = g.RA || {}; RA.${key} = Object.assign(RA.${key} || {}, ${JSON.stringify(map)}); })(typeof window !== "undefined" ? window : globalThis);\n`;
};
fs.writeFileSync(path.join(OUT, "checkpoints.js"), bundle("checkpoints", "HARNESS"));
fs.writeFileSync(path.join(OUT, "solutions.js"), bundle("solutions", "SOLUTIONS"));
fs.writeFileSync(path.join(OUT, "manifest.json"), JSON.stringify({ order: ORDER.concat(["checkpoints", "solutions"]), built: new Date().toISOString() }, null, 2));
console.log("web/curriculum: " + (ORDER.length + 2) + " files");
