// Generates RootAccess.swiftpm/Curriculum.swift: the exact same curriculum + checkpoint engine the web app runs,
// embedded as raw strings and evaluated in JavaScriptCore by Engine.swift. Run after tools/build.js.
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, ".."), WEB = path.join(ROOT, "web");
const html = fs.readFileSync(path.join(WEB, "index.html"), "utf8");
const files = [...html.matchAll(/src="(curriculum\/[^"]+\.js)"/g)].map((x) => path.join(WEB, x[1]));
files.push(path.join(__dirname, "swift-bridge.js"));
const chunks = files.map((f) => {
  const s = fs.readFileSync(f, "utf8");
  if (s.includes('"""##') || s.includes("\\##")) throw new Error("raw-string delimiter collision in " + f);
  return `    // ${path.relative(ROOT, f)}\n    ##"""\n${s}\n"""##`;
});
const out = `// GENERATED by tools/gen-swift.js. Do not edit; edit curriculum/ and rerun \`node tools/build.js && node tools/gen-swift.js\`.
// The Swift app evaluates these scripts in JavaScriptCore so missions, briefs and checkpoint harnesses
// are byte-for-byte the ones the web app and GitHub Actions use.
let CURRICULUM_SCRIPTS: [String] = [
${chunks.join(",\n")}
]
`;
fs.writeFileSync(path.join(ROOT, "RootAccess.swiftpm", "Curriculum.swift"), out);
console.log("Curriculum.swift:", files.length, "scripts,", (out.length / 1024).toFixed(0) + "K");
